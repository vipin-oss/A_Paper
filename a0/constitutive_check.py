"""Exact algebra and symmetry checks for the single H energy coupling.

No literature novelty conclusion follows from these checks.
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
import sympy as s


def run():
    # Engineering strain s=(eps11,eps33,2eps13); g=(s_,1,s_,3).
    x = s.Matrix(s.symbols('s0:3'))
    g = s.Matrix(s.symbols('g0:6'))
    E = s.Matrix(s.symbols('E0:2'))
    nu, a, q, phi = s.symbols('nu a q phi', nonzero=True)
    def symmetric(n, prefix):
        vals = {(i, j): s.Symbol(f'{prefix}{i}{j}') for i in range(n) for j in range(i, n)}
        return s.Matrix(n, n, lambda i, j: vals[min(i,j), max(i,j)])
    C, A = symmetric(3, 'C'), symmetric(6, 'A')
    e = s.Matrix(2, 3, lambda i,j: s.Symbol(f'e{i}{j}'))
    f = s.Matrix(2, 6, lambda i,j: s.Symbol(f'f{i}{j}'))
    h = s.Matrix(s.symbols('h0:6'))
    kap = symmetric(2, 'k')
    energy = ((x.T*C*x)[0]/2 + (g.T*A*g)[0]/2
              -(E.T*e*x)[0]-(E.T*f*g)[0]-(E.T*kap*E)[0]/2
              + a*nu**2/2 + nu*(h.T*g)[0] - q*nu*phi)
    stress = s.Matrix([s.diff(energy,v) for v in x])
    hyper = s.Matrix([s.diff(energy,v) for v in g])
    D = s.Matrix([-s.diff(energy,v) for v in E])
    mu = s.diff(energy,nu)
    assert stress == C*x-e.T*E
    assert hyper == A*g-f.T*E+nu*h
    assert D == e*x+f*g+kap*E
    assert s.expand(mu-(a*nu+(h.T*g)[0]-q*phi)) == 0
    assert hyper.jacobian([nu]) == s.Matrix([mu]).jacobian(g).T
    variables = list(x)+list(g)+list(E)+[nu,phi]
    Hess = s.hessian(energy,variables)
    assert Hess == Hess.T
    # Eliminating nu is locally coefficient-renormalizing ONLY in special limits.
    reduced = s.expand(energy.subs(nu, (q*phi-(h.T*g)[0])/a))
    expected = s.expand(energy.subs(nu,0) - (q*phi-(h.T*g)[0])**2/(2*a))
    assert s.simplify(reduced-expected) == 0
    L, Q2, omega = s.symbols('L Q2 omega', positive=True, real=True)
    dynamic_factor = L*Q2/(L*a*Q2-s.I*omega)
    assert s.simplify(s.diff(dynamic_factor,omega)) != 0

    # Exact point-group reduction of a polar rank-3 tensor H_jkl=H_kjl.
    pairs = [(j,k,l) for j in range(3) for k in range(j,3) for l in range(3)]
    hv = s.symbols(f'H0:{len(pairs)}')
    lookup = {p:v for p,v in zip(pairs,hv)}
    def H(j,k,l): return lookup[min(j,k),max(j,k),l]
    c, sn = s.Rational(1,2), s.sqrt(3)/2
    rot = s.Matrix([[c,-sn,0],[sn,c,0],[0,0,1]])
    mirror = s.diag(1,-1,1)
    constraints = []
    for T in [rot,mirror]:
        for j,k,l in pairs:
            transformed = sum(T[j,p]*T[k,r]*T[l,t]*H(p,r,t)
                              for p in range(3) for r in range(3) for t in range(3))
            constraints.append(s.expand(transformed-H(j,k,l)))
    mat, _ = s.linear_eq_to_matrix(constraints,hv)
    null = mat.nullspace()
    assert len(null) == 3
    ha,hb,hc = s.symbols('h_a h_b h_c')
    prescribed = {(2,2,2):ha, (0,0,2):hb, (1,1,2):hb,
                  (0,2,0):hc, (1,2,1):hc}
    vector = s.Matrix([prescribed.get(p,0) for p in pairs])
    assert s.simplify(mat*vector) == s.zeros(mat.rows,1)
    assert vector.jacobian([ha,hb,hc]).rank() == 3

    # A dimensional exponent check (J, m, C, s); nu is number per volume.
    def plus(*terms): return tuple(sum(t[i] for t in terms) for i in range(4))
    dim_nu=(0,-3,0,0); dim_g=(0,-1,0,0); dim_H=(1,1,0,0)
    assert plus(dim_nu,dim_H,dim_g) == (1,-3,0,0)  # J/m^3
    assert plus(dim_nu,dim_H) == (1,-2,0,0)  # hyperstress N/m
    assert plus(dim_H,dim_g) == (1,0,0,0)  # chemical energy per carrier

    # Numerical independent Schur-complement tests, dimensionless random SPD A.
    rng = np.random.default_rng(84327)
    R = rng.normal(size=(6,6))
    An = R.T@R+np.eye(6)
    direction = rng.normal(size=6)
    direction /= np.sqrt(direction@np.linalg.solve(An,direction))
    checks = []
    for eta in [0.,.25,.5,.8,1.01]:
        hn = eta*direction
        block = np.block([[An,hn[:,None]],[hn[None,:],np.ones((1,1))]])
        schur = float(1-hn@np.linalg.solve(An,hn))
        mineig = float(np.linalg.eigvalsh(block)[0])
        assert (mineig > 0) == (eta < 1)
        checks.append(dict(eta=eta, schur=schur, minimum_eigenvalue=mineig))
    return dict(symbolic_constitutive_derivatives=True,
                complete_potential_Hessian_reciprocity=True,
                symmetry_group='6mm generated by 60-degree rotation and vertical mirror',
                independent_H_components=len(null),
                components={'H333':'h_a', 'H113=H223':'h_b',
                            'H131=H311=H232=H322':'h_c'},
                units_checked=True, carrier_elimination_identity=True,
                dynamic_elimination_frequency_dependent=True,
                dimensionless_schur_tests=checks,
                warning='Algebra verified; literature novelty and measured H are NOT verified.')


if __name__ == '__main__':
    print(json.dumps(run(),indent=2))
